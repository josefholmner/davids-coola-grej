"""Regenerate Rust vocabulary declarations from the curated bilingual metadata."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
words=json.loads((root/'assets/reading/vocabulary.json').read_text(encoding='utf-8'))
assert all(3<=len(word['swedish'])<=7 and 3<=len(word['english'])<=7 for word in words)
assert len(set(word['swedish'] for word in words))==len(words)
assert len(set(word['english'] for word in words))==len(words)
assert [word['id'] for word in words]==list(range(len(words)))
source='''// Generated by tools/generate-vocabulary.py from assets/reading/vocabulary.json.
use crate::language::Language;
pub struct Word { pub swedish: &'static str, pub english: &'static str }
impl Word { pub fn text(&self,language:Language)->&'static str {language.text(self.swedish,self.english)} }
'''
source+='pub const WORD_COUNT: usize = '+str(len(words))+';\npub static WORDS: [Word; WORD_COUNT] = [\n'
for word in words:
    source+='    Word {swedish: '+json.dumps(word['swedish'],ensure_ascii=False)+',english: '+json.dumps(word['english'])+'},\n'
source+=''' ];
pub static IMAGES:[&[u8];WORD_COUNT]=include!(concat!(env!("OUT_DIR"),"/reading_images.rs"));
pub fn word_length(level:u32)->usize{(3+level.saturating_sub(1) as usize/2).min(7)}
pub fn pool(level:u32,language:Language)->Vec<usize>{let length=word_length(level);WORDS.iter().enumerate().filter(|(_,word)|word.text(language).chars().count()==length).map(|(index,_)|index).collect()}
#[cfg(test)]mod tests{use super::*;#[test]fn bilingual_vocabulary_is_graded(){assert_eq!(WORDS.len(),220);for language in [Language::Swedish,Language::English]{let mut unique=std::collections::HashSet::new();for word in &WORDS{assert!((3..=7).contains(&word.text(language).chars().count()));assert!(unique.insert(word.text(language)));}for level in 1..=20{let words=pool(level,language);assert!(words.len()>=2);assert!(words.iter().all(|id|WORDS[*id].text(language).chars().count()==word_length(level)));}}}}
'''
(root/'src/vocabulary.rs').write_text(source,encoding='utf-8')
(root/'assets/reading/image-files.txt').write_text('\n'.join(word['image'] for word in words)+'\n',encoding='utf-8')
print('Generated',len(words),'bilingual entries.')
